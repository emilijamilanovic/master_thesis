# ****************************************************************************
# Stream parent class
# ****************************************************************************
class Stream:
    def __init__(self, *args, **kwargs):
        raise NotImplementedError

    def chunks(self, *args, **kwargs):
        raise NotImplementedError

    def response(self, dump=None):
        r = ''

        for chunk in self.chunks():
            if dump:
                dump.write(chunk)
                dump.flush()

            r += chunk

        if dump:
            dump.write(f'\n\ntokens: {self.prompt_tokens}'
                + f' + {self.completion_tokens}\n\n')

        return r

# ****************************************************************************
# Dummy stream
# ****************************************************************************
class DummyStream(Stream):
    def __init__(self, cfg, user_query, system_prompt = None):
        s = ''

        if system_prompt:
            s += system_prompt + '\n\n'

        if type(user_query) is str:
            s += user_query
        else:
            q = ''
            for msg in user_query:
                if msg['role'] == 'system':
                    s += msg['content'] + '\n\n'
                elif msg['role'] == 'user':
                    q = msg['content']
            s += q

        self.echo = re.findall(r'\w+|.|\n', s)
        self.prompt_tokens = 0
        self.completion_tokens = 0
        self.total_tokens = 0

        self.delay = cfg['token_delay'] if 'token_delay' in cfg else 0.02

    def chunks(self):
        for r in self.echo:
            time.sleep(self.delay)
            yield r

