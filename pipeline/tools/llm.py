"""
# Simple wrapper for the ways we use LLMs.

It is used as follows:

    import tools

    ai = tools.LLM(purpose='dummy')
    stream = ai.query('What is a parrot?')
    print(stream.response())

LLM(purpose='general') constructor:

  - purpose (str, default: 'general')
    Our intended use of the LLM. See purposes.py for supported values.
    The idea is for this purpose to determine a series of configuration
    parameters such as:
    - which LLM model and provider is chosen
    - optionally, a system prompt
    - a limit on the number of generated tokens
    - temperature and other inference parameters

LLM.query(user_query):

  - user_query (either str or iterable)
    - str: the LLM prompt
    - iterable: a sequence of
          { 'role': <role>, 'content': <content> }
      dictionaries with two entries:
      - 'role': string, one of 'system', 'user' or 'assistant'
      - 'content': the corresponding system prompt, user prompt, or LLM
        response, respectively
      Passing an iterable user_query enables a conversation mode in which
      the LLM knows of previous user prompts and of its own previous
      responses.

  Return value: a Stream object. This object has two relevant methods:

  - Stream.response() waits for the complete LLM response and returns it
    as a string.

  - Stream.chunks() returns an iterable which allows us to stream response
    tokens (strings) as they are generated by the LLM.

  See purposes.py for details. Under the hood, all arguments passed to
  llm.LLM.query() are simply forwarded to the constructor of this Stream
  class.

# Purposes for LLM uses.

Currently supported values:

- 'dummy': a trivial test config that just returns the prompt as a response
- 'general': a general-purpose config, currently using OpenAI as the
  default provider (see the 'defaults' entry in the configs dict below).
  Other providers ('anthropic', 'gemini', 'fireworks', 'hyperbolic') can
  be selected with LLM(purpose='anthropic') or
  ai.override({'include': ['anthropic']}).

The config field is a dictionary of configuration parameters.

One can override individual parameters after LLM() construction as follows:

    ai = tools.LLM(purpose = 'general')
    ai.config['model_shortcut'] = 'fast'

A particular entry in this dictionary has the key 'query_streamer'.
The corresponding value is a class derived from Stream. An instance
of this class is created in and returned by LLM.query(). Parameters to
LLM.query() are forwarded to the constructor.

# Embeddings

Embedding vectors can be computed as follows:

    ai = tools.llm.LLM(purpose='embed')
    vector = ai.embed(text).vector()

where text is a string, and we obtain the vector as list of floats.

"""
