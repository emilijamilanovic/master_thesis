# ****************************************************************************
# Entry point
# ****************************************************************************
class LLM:
    def __init__(self, purpose='general'):
        self.config = {}
        self.override({ 'include': [ 'defaults' ] })
        if type(purpose) is str:
            self.override({ 'include': purpose.split() })

    def override(self, cfg):
        for key in cfg:
            if key == 'include':
                for purpose in cfg['include']:
                    if purpose not in configs:
                        raise ValueError(f'Unknown purpose "{purpose}". '
                            f'Known: {", ".join(sorted(configs))}')
                    self.override(configs[purpose])
            else:
                self.config[key] = cfg[key]

    def query(self, *args, **kwargs):
        streamer = self.config['query_streamer']
        return streamer(self.config, *args, **kwargs)

    def embed(self, *args, **kwargs):
        embedder = self.config['embedder']
        return embedder(self.config, *args, **kwargs)

class MessageBuilder:
    def __init__(self, options = None):
        self.options = options or {}

    def generic(self, role, content):
        return { 'role': role, 'content': content }

    def system(self, content):
        return self.generic('system', content)

    def user(self, content):
        return self.generic('user', content)

    def assistant(self, content):
        return self.generic('assistant', content)

