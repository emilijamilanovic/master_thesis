class Embedder:
    def __init__(self, *args, **kwargs):
        raise NotImplementedError

    def vector(self, *args, **kwargs):
        raise NotImplementedError

class DummyEmbedder(Embedder):
    def __init__(self, cfg, text):
        self.prompt_tokens = 0
        self.total_tokens = 0

    def vector(self):
        return [ 1.0, 0.0, 0.0 ]

class EmbeddingsEmbedder(Embedder):
    def __init__(self, cfg, text):
        client = openai.OpenAI(
            base_url=cfg['base_url'],
            api_key=api_key(cfg),
        )

        if 'embedding_model' in cfg:
            model = cfg['embedding_model']
        elif 'embedding_shortcut' in cfg:
            shortcut = cfg['embedding_shortcut']
            model = cfg['embedding_shortcuts'][shortcut]
        else:
            raise ValueError('embedding model not specified in configuration')

        params = { 'model': model, 'input': text, 'timeout': 5.0 }

        self.response = client.embeddings.create(**params)

        self.prompt_tokens = self.response.usage.prompt_tokens
        self.total_tokens = self.response.usage.total_tokens

    def vector(self):
        return self.response.data[0].embedding

