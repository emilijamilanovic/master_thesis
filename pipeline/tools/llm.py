# API key resolution
# ****************************************************************************
def api_key(cfg):
    """Resolve a provider's API key.

    Keys are read from the environment at call time (not at import time),
    so loading a .env file after importing this module still works.
    An explicit cfg['api_key'] takes precedence if one is set.
    """
    key = cfg.get('api_key') or os.environ.get(cfg.get('api_key_env', ''))
    if not key:
        raise ValueError(
            f'No API key for the provider at {cfg.get("base_url")}. '
            f'Set {cfg.get("api_key_env", "the provider key")} in .env and '
            'load it (run_pipeline.py does this automatically; for manual '
            'runs: set -a; source .env; set +a).')
    return key


class CompletionStream(Stream):
    def __init__(self, cfg, user_query, system_prompt=None):
        # Reasoning models emit thinking tokens before the answer and can
        # leave the stream idle for a long time between chunks, which the
        # SDK's default read timeout treats as a dead connection. A generous
        # timeout plus a few retries turns that into a slow run rather than a
        # failed batch. Override per provider with cfg['timeout'] /
        # cfg['max_retries'] if one of them needs different limits.
        client = openai.OpenAI(
            base_url=cfg['base_url'],
            api_key=api_key(cfg),
            timeout=cfg.get('timeout', 600.0),
            max_retries=cfg.get('max_retries', 3),
        )

        msg = []

        if 'system_prompt' in cfg:
            msg.append({ 'role': 'system', 'content': cfg['system_prompt'] })

        if system_prompt:
            msg.append({ 'role': 'system', 'content': system_prompt })

        if type(user_query) is str:
            msg.append({ 'role': 'user', 'content': user_query })
        else:
            for m in user_query:
                msg.append(m)

        if 'model' in cfg:
            model = cfg['model']
        elif 'model_shortcut' in cfg:
            shortcut = cfg['model_shortcut']
            model = cfg['model_shortcuts'][shortcut]
        else:
            raise ValueError('model not specified in configuration')

        params = { 'stream': True, 'model': model, 'messages': msg }

        # 'reasoning_effort' is forwarded so that a provider config can turn
        # thinking off (see 'fireworks' below). It is only ever sent when a
        # config sets it, so providers that do not accept the parameter are
        # unaffected.
        direct_copy = { 'temperature', 'top_p', 'top_k', 'n', 'max_tokens',
                        'stop', 'presence_penalty', 'frequency_penalty',
                        'reasoning_effort' }

        for key in cfg:
            if key in direct_copy:
                params[key] = cfg[key]

        self.stream = client.chat.completions.create(**params)

        self.prompt_tokens = 0
        self.completion_tokens = 0
        self.total_tokens = 0

    def chunks(self):
        for chunk in self.stream:
            # Providers differ here: Fireworks sends a final usage-only
            # chunk with an empty choices list, and reasoning models send
            # chunks whose delta has no visible content. Both are normal.
            if chunk.choices:
                s = chunk.choices[0].delta.content

                if s is not None:
                    yield s

            usage = getattr(chunk, 'usage', None)
            if usage:
                self.prompt_tokens = usage.prompt_tokens
                self.completion_tokens = usage.completion_tokens
                self.total_tokens = usage.total_tokens


